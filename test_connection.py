import socket
import pytest

HOST = "127.0.0.1"
PORT = 2001
TIMEOUT = 5.0


@pytest.mark.usefixtures("signal_service")
def test_tcp_connection_established():
    """
    Автотест критичного сценария: установка TCP-соединения
    с сервисом-симулятором на порту 2001.

    Логика:
    1. Фикстура поднимает сервис-симулятор отдельным процессом.
    2. Тест пытается открыть TCP-сокет на 127.0.0.1:2001.
    3. Assert проверяет, что соединение действительно установлено.
    """
    """Соединение с сервисом на порту 2001 должно устанавливаться без ошибок."""

    # Пытаемся подключиться. Если сервис недоступен — socket.create_connection
    # бросит исключение, и тест упадёт с понятной ошибкой.
    with socket.create_connection((HOST, PORT), timeout=TIMEOUT) as sock:
        # Проверяем, что сокет действительно подключён (есть peer)
        peer = sock.getpeername()

    # Assert: соединение установлено, peer совпадает с ожидаемым адресом сервиса
    assert peer == (HOST, PORT), (
        f"Ожидалось соединение с {HOST}:{PORT}, получено {peer}"
    )
